#!/usr/bin/env python3
"""Validates the two catalogue files the app downloads and bundles.

    python tools/validate_catalog.py                  # check both files
    python tools/validate_catalog.py --base origin/master   # also require a revision bump

The files live in the repository root:
  source_catalog.json  which update and news sources a device gets
  device_models.json   model names for the Add device picker
  phone_models.json    phone and tablet names, generated from Google's list by tools/build_phones.py
  support.json         how long phones get security updates, generated by tools/build_support.py

The rules mirror SourceCatalog.kt, ModelList.kt and SupportList.kt in the Kithub app: the app skips a bad entry silently, so
this script is where a typo is caught instead. Exit code 0 = valid, 1 = problems found.
Standard library only.
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "source_catalog.json"
MODELS = ROOT / "device_models.json"
PHONES = ROOT / "phone_models.json"  # generated by tools/build_phones.py
SUPPORT = ROOT / "support.json"  # generated by tools/build_support.py

SUPPORTED_SCHEMA = 1
DEVICE_TYPES = {"Phone", "Watch", "Headphones", "Laptop", "Tablet", "Other"}
KINDS = {"updates", "news"}
SOURCE_KEYS = {"id", "name", "kind", "url", "types", "modelStartsWith", "modelContains", "modelNotStartsWith", "supersededBy", "filterByModel"}
GROUP_KEYS = {"type", "brand", "names", "codes"}
# The same limits as the app (SourceCatalog.kt / ModelList.kt): it skips anything beyond them.
MAX_SOURCES = 200
MAX_URL_LENGTH = 2048
MAX_TEXT_LENGTH = 120
MAX_LIST_SIZE = 50
MAX_NAME_LENGTH = 100
MAX_NAMES = 100_000
MAX_CODE_LENGTH = 40
MAX_CODES = 100_000
MAX_SUPPORT_MODELS = 5000
SUPPORT_SOURCE_KEYS = {"brand", "url", "modelStartsWith", "types", "complete"}
SUPPORT_MODEL_KEYS = {"brand", "name", "until", "ended", "cadence"}
CADENCES = {"monthly", "bimonthly", "quarterly", "biannual", "regular"}


class Problems:
    def __init__(self, label):
        self.label = label
        self.items = []

    def add(self, where, message):
        self.items.append(f"{self.label}: {where}: {message}")


def load(path, problems):
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        problems.add(path.name, "file not found")
        return None
    except json.JSONDecodeError as e:
        problems.add(path.name, f"not valid JSON ({e})")
        return None
    if not isinstance(data, dict):
        problems.add(path.name, "top level must be an object")
        return None
    version = data.get("schemaVersion")
    if not isinstance(version, int) or isinstance(version, bool) or not 1 <= version <= SUPPORTED_SCHEMA:
        problems.add("schemaVersion", f"must be an integer from 1 to {SUPPORTED_SCHEMA}, is {version!r}")
        return None
    return data


def string_list(entry, key, where, problems, allow_empty=True):
    value = entry.get(key, [])
    if not isinstance(value, list) or not all(isinstance(v, str) and v.strip() for v in value):
        problems.add(where, f'"{key}" must be a list of non-empty strings')
        return []
    if not allow_empty and not value:
        problems.add(where, f'"{key}" must not be empty')
    # Model names have their own, larger limits (check_models).
    if key != "names":
        if len(value) > MAX_LIST_SIZE:
            problems.add(where, f'"{key}" has {len(value)} entries; the app reads at most {MAX_LIST_SIZE}')
        if any(len(item) > MAX_TEXT_LENGTH for item in value):
            problems.add(where, f'"{key}" has an entry longer than {MAX_TEXT_LENGTH} characters')
    return value


def check_revision(data, problems):
    revision = data.get("revision")
    if not isinstance(revision, int) or isinstance(revision, bool) or revision < 1:
        problems.add("revision", f"must be an integer of 1 or more, is {revision!r}")


def check_sources(data, problems):
    check_revision(data, problems)
    sources = data.get("sources")
    if not isinstance(sources, list) or not sources:
        problems.add("sources", "must be a non-empty list")
        return
    if len(sources) > MAX_SOURCES:
        problems.add("sources", f"{len(sources)} sources; the app reads at most {MAX_SOURCES}")
    ids = [s.get("id") for s in sources if isinstance(s, dict)]
    seen = set()
    for index, source in enumerate(sources):
        where = f"sources[{index}]"
        if not isinstance(source, dict):
            problems.add(where, "must be an object")
            continue
        sid = source.get("id")
        where = f'sources[{index}] ({sid})'
        for key in ("id", "name", "url"):
            if not isinstance(source.get(key), str) or not source[key].strip():
                problems.add(where, f'"{key}" is required')
        if isinstance(sid, str):
            if sid in seen:
                problems.add(where, "duplicate id")
            seen.add(sid)
        for key in ("id", "name"):
            if isinstance(source.get(key), str) and len(source[key]) > MAX_TEXT_LENGTH:
                problems.add(where, f'"{key}" is longer than {MAX_TEXT_LENGTH} characters')
        if source.get("kind") not in KINDS:
            problems.add(where, f'"kind" must be one of {sorted(KINDS)}')
        url = source.get("url")
        if isinstance(url, str):
            if len(url.strip()) > MAX_URL_LENGTH:
                problems.add(where, f"url is longer than {MAX_URL_LENGTH} characters")
            parsed = urlparse(url.strip())
            if parsed.scheme != "https" or "." not in (parsed.hostname or ""):
                problems.add(where, f"url must be https with a host: {url}")
        types = string_list(source, "types", where, problems)
        for t in types:
            if t not in DEVICE_TYPES:
                problems.add(where, f'unknown device type "{t}" (use {sorted(DEVICE_TYPES)})')
        starts = string_list(source, "modelStartsWith", where, problems)
        contains = string_list(source, "modelContains", where, problems)
        # Only narrows: it does not count as the rule a source needs.
        string_list(source, "modelNotStartsWith", where, problems)
        if not types and not starts and not contains and source.get("filterByModel") is not True:
            problems.add(
                where,
                'no "types", "modelStartsWith" or "modelContains": it would go to every device '
                '(the app skips it unless it is a news source with "filterByModel": true)',
            )
        for ref in string_list(source, "supersededBy", where, problems):
            if ref == sid:
                problems.add(where, "supersededBy points at itself")
            elif ref not in ids:
                problems.add(where, f'supersededBy "{ref}" is not a source id')
        if "filterByModel" in source:
            if not isinstance(source["filterByModel"], bool):
                problems.add(where, '"filterByModel" must be true or false')
            elif source["filterByModel"] and source.get("kind") != "news":
                problems.add(where, '"filterByModel" only applies to news sources (the app ignores it for updates)')
        for key in source:
            if key not in SOURCE_KEYS:
                problems.add(where, f'unknown field "{key}" (the app ignores it)')


def check_models(data, problems):
    check_revision(data, problems)
    groups = data.get("groups")
    if not isinstance(groups, list) or not groups:
        problems.add("groups", "must be a non-empty list")
        return
    seen = {}
    total = 0
    code_owner = {}  # code, lower case -> where it is listed
    for index, group in enumerate(groups):
        where = f"groups[{index}]"
        if not isinstance(group, dict):
            problems.add(where, "must be an object")
            continue
        gtype = group.get("type")
        if gtype not in DEVICE_TYPES:
            problems.add(where, f'"type" must be one of {sorted(DEVICE_TYPES)}, is {gtype!r}')
        brand = group.get("brand", "")
        if not isinstance(brand, str):
            problems.add(where, '"brand" must be a string ("" when names already include it)')
            brand = ""
        names = string_list(group, "names", where, problems, allow_empty=False)
        for name in names:
            if len(name.strip()) < 2:
                problems.add(where, f'name "{name}" is too short')
            if len(name.strip()) > MAX_NAME_LENGTH:
                problems.add(where, f'name "{name[:30]}..." is longer than {MAX_NAME_LENGTH} characters')
            shown = name if brand and name.lower().startswith(brand.lower()) else f"{brand} {name}".strip()
            key = (gtype, shown.lower())
            if key in seen:
                problems.add(where, f'"{shown}" is listed twice ({gtype})')
            seen[key] = True
        total += len(names)
        if "codes" in group:
            check_codes(group["codes"], names, where, code_owner, problems)
        for key in group:
            if key not in GROUP_KEYS:
                problems.add(where, f'unknown field "{key}" (the app ignores it)')


    if total > MAX_NAMES:
        problems.add("groups", f"{total} names; the app reads at most {MAX_NAMES}")
    if len(code_owner) > MAX_CODES:
        problems.add("groups", f"{len(code_owner)} model codes; the app reads at most {MAX_CODES}")


def check_codes(codes, names, where, code_owner, problems):
    """"codes": {name: [model codes]}: each name is one of the group's, each code is listed once."""
    if not isinstance(codes, dict):
        problems.add(where, '"codes" must be an object of name -> list of model codes')
        return
    for name, values in codes.items():
        if name not in names:
            problems.add(where, f'"codes" has "{name}", which is not in "names"')
        if not isinstance(values, list) or not values or not all(isinstance(v, str) and v.strip() for v in values):
            problems.add(where, f'"codes" for "{name}" must be a non-empty list of non-empty strings')
            continue
        for code in values:
            if len(code) > MAX_CODE_LENGTH:
                problems.add(where, f'code "{code[:30]}..." is longer than {MAX_CODE_LENGTH} characters')
            key = code.strip().lower()
            if key in code_owner:
                problems.add(where, f'code "{code}" is also listed for {code_owner[key]}')
            code_owner[key] = f'"{name}" in {where}'


def check_support(data, problems):
    check_revision(data, problems)
    sources = data.get("sources")
    if not isinstance(sources, list) or not sources:
        problems.add("sources", "must be a non-empty list")
        sources = []
    brands = set()
    for index, source in enumerate(sources):
        where = f"sources[{index}]"
        if not isinstance(source, dict):
            problems.add(where, "must be an object")
            continue
        brand = source.get("brand")
        if not isinstance(brand, str) or not brand.strip() or len(brand) > MAX_TEXT_LENGTH:
            problems.add(where, '"brand" is required (up to 120 characters)')
        else:
            brands.add(brand)
        url = source.get("url")
        if not isinstance(url, str) or urlparse(url).scheme != "https" or len(url) > MAX_URL_LENGTH:
            problems.add(where, '"url" must be the https page the entries come from')
        if not string_list(source, "modelStartsWith", where, problems, allow_empty=False):
            pass
        for t in string_list(source, "types", where, problems, allow_empty=False):
            if t not in DEVICE_TYPES:
                problems.add(where, f'unknown device type "{t}"')
        if not isinstance(source.get("complete"), bool):
            problems.add(where, '"complete" must be true or false')
        for key in source:
            if key not in SUPPORT_SOURCE_KEYS:
                problems.add(where, f'unknown field "{key}" (the app ignores it)')
    models = data.get("models")
    if not isinstance(models, list) or not models:
        problems.add("models", "must be a non-empty list")
        return
    if len(models) > MAX_SUPPORT_MODELS:
        problems.add("models", f"{len(models)} models; the app reads at most {MAX_SUPPORT_MODELS}")
    seen = set()
    for index, model in enumerate(models):
        where = f"models[{index}]"
        if not isinstance(model, dict):
            problems.add(where, "must be an object")
            continue
        brand, name = model.get("brand"), model.get("name")
        where = f"models[{index}] ({name})"
        if brand not in brands:
            problems.add(where, f'"brand" must be one of the sources\' brands {sorted(brands)}')
        if not isinstance(name, str) or len(name.strip()) < 2 or len(name) > MAX_NAME_LENGTH:
            problems.add(where, '"name" is required (2 to 100 characters)')
            continue
        if (brand, name.lower()) in seen:
            problems.add(where, "listed twice")
        seen.add((brand, name.lower()))
        kinds = [k for k in ("until", "ended", "cadence") if k in model]
        if len(kinds) != 1:
            problems.add(where, 'needs exactly one of "until", "ended" or "cadence"')
        if "until" in model and not (isinstance(model["until"], str) and re.fullmatch(r"\d{4}-(0[1-9]|1[0-2])", model["until"])):
            problems.add(where, '"until" must be "YYYY-MM"')
        if "ended" in model and model["ended"] is not True:
            problems.add(where, '"ended" must be true')
        if "cadence" in model and model["cadence"] not in CADENCES:
            problems.add(where, f'"cadence" must be one of {sorted(CADENCES)}')
        for key in model:
            if key not in SUPPORT_MODEL_KEYS:
                problems.add(where, f'unknown field "{key}" (the app ignores it)')


def git_show(ref, path):
    rel = path.relative_to(ROOT).as_posix()
    result = subprocess.run(
        ["git", "show", f"{ref}:{rel}"], cwd=ROOT, capture_output=True, text=True, encoding="utf-8"
    )
    return result.stdout if result.returncode == 0 else None


def check_revision_bump(path, base, problems):
    """A changed file with the same revision never reaches installs that already have the old one."""
    old_text = git_show(base, path)
    if old_text is None:
        return  # new file: nothing to compare with
    new_text = path.read_text(encoding="utf-8")
    try:
        old, new = json.loads(old_text), json.loads(new_text)
    except json.JSONDecodeError:
        return
    if old == new:
        return
    if not new.get("revision", 0) > old.get("revision", 0):
        problems.add(
            "revision",
            f"{path.name} changed but revision is still {new.get('revision')}: bump it "
            f"(was {old.get('revision')} on {base})",
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--base", help="git ref to compare against (e.g. origin/master) and require a revision bump")
    args = parser.parse_args()

    all_problems = []

    p = Problems("source_catalog.json")
    data = load(SOURCES, p)
    if data is not None:
        check_sources(data, p)
        if args.base:
            check_revision_bump(SOURCES, args.base, p)
    all_problems += p.items
    count = len(data.get("sources", [])) if isinstance(data, dict) else 0

    q = Problems("device_models.json")
    models = load(MODELS, q)
    if models is not None:
        check_models(models, q)
        if args.base:
            check_revision_bump(MODELS, args.base, q)
    all_problems += q.items
    names = sum(
        len(g.get("names", [])) for g in (models or {}).get("groups", []) if isinstance(g, dict)
        and isinstance(g.get("names"), list)
    )

    r = Problems("phone_models.json")
    phones = load(PHONES, r)
    if phones is not None:
        check_models(phones, r)
        if args.base:
            check_revision_bump(PHONES, args.base, r)
    all_problems += r.items
    phone_names = sum(
        len(g.get("names", [])) for g in (phones or {}).get("groups", []) if isinstance(g, dict)
        and isinstance(g.get("names"), list)
    )

    t = Problems("support.json")
    support = load(SUPPORT, t)
    if support is not None:
        check_support(support, t)
        if args.base:
            check_revision_bump(SUPPORT, args.base, t)
    all_problems += t.items
    support_models = len((support or {}).get("models", []) or [])

    if all_problems:
        print("Catalogue is not valid:")
        for line in all_problems:
            print("  -", line)
        return 1
    print(
        f"OK: source_catalog.json revision {data.get('revision')}, {count} sources; "
        f"device_models.json revision {models.get('revision')}, {names} model names; "
        f"phone_models.json revision {phones.get('revision')}, {phone_names} phone names; "
        f"support.json revision {support.get('revision')}, {support_models} models"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
